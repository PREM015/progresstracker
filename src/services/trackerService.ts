  /**
   * Validate import data
   */
  static validateImportData(data: unknown[]): {
    valid: TrackerEntryInput[];
    errors: { row: number; error: string }[];
  } {
    const valid: TrackerEntryInput[] = [];
    const errors: { row: number; error: string }[] = [];

    for (let i = 0; i < data.length; i++) {
      const row = data[i] as Record<string, unknown>;

      // Required fields
      if (!row.date) {
        errors.push({ row: i + 1, error: "Missing required field: date" });
        continue;
      }

      // Validate date
      const date = new Date(row.date as string);
      if (isNaN(date.getTime())) {
        errors.push({ row: i + 1, error: "Invalid date format" });
        continue;
      }

      // Build valid entry
      const entry: Partial<TrackerEntryInput> = {
        date,
        userId: "", // Will be set during import
      };

      // Map numeric fields
      const numericFields = [
        "problemsSolved",
        "commits",
        "timeSpent",
        "easyProblems",
        "mediumProblems",
        "hardProblems",
      ];

      for (const field of numericFields) {
        if (row[field] !== undefined) {
          const value = Number(row[field]);
          if (!isNaN(value) && value >= 0) {
            (entry as Record<string, unknown>)[field] = value;
          }
        }
      }

      // Map string fields
      if (row.notes && typeof row.notes === "string") {
        entry.notes = row.notes;
      }
      if (row.platformId && typeof row.platformId === "string") {
        entry.platformId = row.platformId;
      }

      // Map array fields
      if (Array.isArray(row.tags)) {
        entry.tags = row.tags.filter((t): t is string => typeof t === "string");
      }

      valid.push(entry as TrackerEntryInput);
    }

    return { valid, errors };
  }

