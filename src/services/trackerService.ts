  /**
   * Get entries for a date range with filters
   */
  static async getEntries(
    userId: string,
    startDate: Date,
    endDate: Date,
    filters?: TrackerEntryFilters,
    options?: {
      page?: number;
      limit?: number;
      sortBy?: string;
      sortOrder?: "asc" | "desc";
      include?: {
        platform?: boolean;
        customPlatform?: boolean;
        syncLog?: boolean;
      };
      select?: Prisma.TrackerEntrySelect;
    }
  ) {
    const { page = 1, limit = 50, sortBy = "date", sortOrder = "desc", include } = options ?? {};

    // Build where clause
    const where: Prisma.TrackerEntryWhereInput = {
      userId,
      date: {
        gte: startDate,
        lte: endDate,
      },
    };

    // Apply filters
    if (filters) {
      if (filters.platformId) {
        where.platformId = filters.platformId;
      }
      if (filters.customPlatformId) {
        where.customPlatformId = filters.customPlatformId;
      }
      if (filters.category) {
        where.category = filters.category;
      }
      if (filters.categories && filters.categories.length > 0) {
        where.category = { in: filters.categories };
      }
      if (filters.source) {
        where.source = filters.source;
      }
      if (filters.tags && filters.tags.length > 0) {
        where.tags = { hasSome: filters.tags };
      }
      if (filters.topics && filters.topics.length > 0) {
        where.topics = { hasSome: filters.topics };
      }
      if (filters.languages && filters.languages.length > 0) {
        where.languages = { hasSome: filters.languages };
      }
      if (filters.hasMood !== undefined) {
        where.mood = filters.hasMood ? { not: null } : null;
      }
      if (filters.hasNotes !== undefined) {
        where.notes = filters.hasNotes ? { not: null } : null;
      }
      if (filters.isVerified !== undefined) {
        where.isVerified = filters.isVerified;
      }
      if (filters.minProblems !== undefined) {
        where.problemsSolved = { gte: filters.minProblems };
      }
      if (filters.minCommits !== undefined) {
        where.commits = { gte: filters.minCommits };
      }
      if (filters.minTimeSpent !== undefined) {
        where.timeSpent = { gte: filters.minTimeSpent };
      }
    }

    // Get total count
    const total = await prisma.trackerEntry.count({ where });

    // Build include clause
    const includeClause: Prisma.TrackerEntryInclude = {};

    // Default includes if not specified to prevent N+1
    if (!options?.select && !include) {
      includeClause.platform = true;
      includeClause.customPlatform = true;
    } else {
      if (include?.platform) includeClause.platform = true;
      if (include?.customPlatform) includeClause.customPlatform = true;
      if (include?.syncLog) includeClause.syncLog = true;
    }

    // Build findMany arguments
    const findManyArgs: Prisma.TrackerEntryFindManyArgs = {
      where,
      orderBy: { [sortBy]: sortOrder as Prisma.SortOrder },
      ...paginationArgs(page, limit),
    };

    if (options?.select) {
      findManyArgs.select = options.select;
    } else if (Object.keys(includeClause).length > 0) {
      findManyArgs.include = includeClause;
    }

    // Generate cache key for dashboard view (page 1, default sort, no filters)
    const isDashboardView = page === 1 && limit <= 20 && !filters && sortBy === 'date' && sortOrder === 'desc';
    const cacheKey = `tracker:entries:${userId}:dashboard`;

    if (isDashboardView) {
      const cached = await CacheService.get(cacheKey);
      if (cached) return cached;
    }

    // Get entries
    const entries = await prisma.trackerEntry.findMany(findManyArgs);

    const result = buildPaginationResponse(entries, total, page, limit);

    if (isDashboardView) {
      await CacheService.set(cacheKey, result, 60 * 5); // Cache for 5 mins
    }

    return result;
  }

  /**
   * Get all entries for a date range (no pagination)
   */
  static async getAllEntries(
    userId: string,
    startDate: Date,
    endDate: Date,
    platformId?: string | null,
    select?: Prisma.TrackerEntrySelect
  ) {
    const where: Prisma.TrackerEntryWhereInput = {
      userId,
      date: {
        gte: startDate,
        lte: endDate,
      },
    };

    if (platformId) {
      where.platformId = platformId;
    }

    const findManyAllArgs: Prisma.TrackerEntryFindManyArgs = {
      where,
      orderBy: { date: "desc" },
    };

    if (select) {
      findManyAllArgs.select = select;
    } else {
      findManyAllArgs.select = {
        id: true,
        date: true,
        platformId: true,
        customPlatformId: true,
        category: true,
        problemsSolved: true,
        easyProblems: true,
        mediumProblems: true,
        hardProblems: true,
        commits: true,
        pullRequests: true,
        timeSpent: true,
        points: true,
        xpEarned: true,
        rating: true,
        ratingChange: true,
        rank: true,
        source: true,
        isVerified: true,
        createdAt: true,
        updatedAt: true,
        platform: {
          select: { id: true, name: true, slug: true, icon: true, color: true },
        },
        customPlatform: {
          select: { id: true, name: true, icon: true, color: true },
        },
      };
    }

    return prisma.trackerEntry.findMany(findManyAllArgs);
  }

  /**
   * Get entry by ID
   */
  static async getEntryById(id: string, userId?: string) {
    const entry = await prisma.trackerEntry.findUnique({
      where: { id },
      include: {
        platform: true,
        customPlatform: true,
        syncLog: true,
      },
    });

    // Verify ownership if userId provided
    if (entry && userId && entry.userId !== userId) {
      return null;
    }

    return entry;
  }

  /**
   * Get entry for specific date and platform
   */
  static async getEntryByDateAndPlatform(
    userId: string,
    date: Date,
    platformId?: string | null,
    customPlatformId?: string | null
  ) {
    // Normalize date to start of day
    const normalizedDate = new Date(date);
    normalizedDate.setHours(0, 0, 0, 0);

    const where: Prisma.TrackerEntryWhereInput = {
      userId,
      date: normalizedDate,
    };

    if (platformId) {
      where.platformId = platformId;
    } else if (customPlatformId) {
      where.customPlatformId = customPlatformId;
    }

    return prisma.trackerEntry.findFirst({
      where,
      include: {
        platform: true,
        customPlatform: true,
      },
    });
  }

  /**
   * Get entries grouped by date
   */
  static async getEntriesGroupedByDate(
    userId: string,
    startDate: Date,
    endDate: Date
  ): Promise<Map<string, Awaited<ReturnType<typeof prisma.trackerEntry.findMany>>>> {
    const entries = await prisma.trackerEntry.findMany({
      where: {
        userId,
        date: {
          gte: startDate,
          lte: endDate,
        },
      },
      orderBy: { date: "desc" },
      include: {
        platform: true,
      },
    });

    const grouped = new Map<string, typeof entries>();

    for (const entry of entries) {
      const dateKey = entry.date.toISOString().split("T")[0];
      if (!grouped.has(dateKey)) {
        grouped.set(dateKey, []);
      }
      grouped.get(dateKey)!.push(entry);
    }

    return grouped;
  }

