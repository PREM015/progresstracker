  /**
   * Get comprehensive statistics for a date range
   */
  static async getStats(
    userId: string,
    startDate: Date,
    endDate: Date,
    platformId?: string | null
  ): Promise<TrackerStats> {
    const where: Prisma.TrackerEntryWhereInput = {
      userId,
      date: {
        gte: startDate,
        lte: endDate,
      },
    };

    if (platformId) {
      where.platformId = platformId;
    }

    // Get aggregates
    const aggregates = await prisma.trackerEntry.aggregate({
      where,
      _sum: {
        problemsSolved: true,
        problemsAttempted: true,
        easyProblems: true,
        mediumProblems: true,
        hardProblems: true,
        commits: true,
        pullRequests: true,
        pullRequestsMerged: true,
        issuesOpened: true,
        issuesClosed: true,
        codeReviews: true,
        coursesCompleted: true,
        certificationsEarned: true,
        lessonsCompleted: true,
        applicationsSubmitted: true,
        interviewsCompleted: true,
        offersReceived: true,
        contestsParticipated: true,
        hackathonsCompleted: true,
        timeSpent: true,
        points: true,
        pointsEarned: true,
      },
      _count: {
        id: true,
      },
    });

    // Get distinct days
    const distinctDays = await prisma.trackerEntry.findMany({
      where,
      select: { date: true },
      distinct: ["date"],
    });

    const totalDays = distinctDays.length;

    // Get platform breakdown
    const platformBreakdown: Record<string, { problems: number; commits: number; timeSpent: number }> =
      {};

    const platformAggregates = await prisma.trackerEntry.groupBy({
      by: ["platformId"],
      where: {
        ...where,
        platformId: { not: null },
      },
      _sum: {
        problemsSolved: true,
        commits: true,
        timeSpent: true,
      },
    });

    for (const pa of platformAggregates) {
      if (pa.platformId) {
        platformBreakdown[pa.platformId] = {
          problems: pa._sum.problemsSolved ?? 0,
          commits: pa._sum.commits ?? 0,
          timeSpent: pa._sum.timeSpent ?? 0,
        };
      }
    }

    // Get category breakdown
    const categoryBreakdown: Record<string, number> = {};

    const categoryAggregates = await prisma.trackerEntry.groupBy({
      by: ["category"],
      where: {
        ...where,
        category: { not: null },
      },
      _sum: {
        problemsSolved: true,
      },
    });

    for (const ca of categoryAggregates) {
      if (ca.category) {
        categoryBreakdown[ca.category] = ca._sum.problemsSolved ?? 0;
      }
    }

    const totalProblems = aggregates._sum.problemsSolved ?? 0;
    const totalCommits = aggregates._sum.commits ?? 0;
    const totalTimeSpent = aggregates._sum.timeSpent ?? 0;

    return {
      // Totals
      totalProblems,
      totalCommits,
      totalPullRequests: aggregates._sum.pullRequests ?? 0,
      totalTimeSpent,
      totalPoints: (aggregates._sum.points ?? 0) + (aggregates._sum.pointsEarned ?? 0),
      totalDays,

      // Difficulty Breakdown
      easyProblems: aggregates._sum.easyProblems ?? 0,
      mediumProblems: aggregates._sum.mediumProblems ?? 0,
      hardProblems: aggregates._sum.hardProblems ?? 0,

      // Development
      pullRequestsMerged: aggregates._sum.pullRequestsMerged ?? 0,
      issuesOpened: aggregates._sum.issuesOpened ?? 0,
      issuesClosed: aggregates._sum.issuesClosed ?? 0,
      codeReviews: aggregates._sum.codeReviews ?? 0,

      // Learning
      coursesCompleted: aggregates._sum.coursesCompleted ?? 0,
      certificationsEarned: aggregates._sum.certificationsEarned ?? 0,
      lessonsCompleted: aggregates._sum.lessonsCompleted ?? 0,

      // Applications
      applicationsSubmitted: aggregates._sum.applicationsSubmitted ?? 0,
      interviewsCompleted: aggregates._sum.interviewsCompleted ?? 0,
      offersReceived: aggregates._sum.offersReceived ?? 0,

      // Competitions
      contestsParticipated: aggregates._sum.contestsParticipated ?? 0,
      hackathonsCompleted: aggregates._sum.hackathonsCompleted ?? 0,

      // Averages
      avgProblemsPerDay: totalDays > 0 ? totalProblems / totalDays : 0,
      avgTimePerDay: totalDays > 0 ? totalTimeSpent / totalDays : 0,
      avgCommitsPerDay: totalDays > 0 ? totalCommits / totalDays : 0,

      // Breakdowns
      platformBreakdown,
      categoryBreakdown,
    };
  }

  /**
   * Get heatmap data for calendar visualization
   */
  static async getHeatmapData(
    userId: string,
    year: number
  ): Promise<{ date: string; count: number; level: number }[]> {
    const startDate = new Date(year, 0, 1);
    const endDate = new Date(year, 11, 31);

    const dailyStats = await prisma.trackerEntry.groupBy({
      by: ["date"],
      where: {
        userId,
        date: {
          gte: startDate,
          lte: endDate,
        },
      },
      _sum: {
        problemsSolved: true,
        commits: true,
      },
    });

    // Find max activity for level calculation
    const maxActivity = Math.max(
      ...dailyStats.map((d) => (d._sum.problemsSolved ?? 0) + (d._sum.commits ?? 0)),
      1
    );

    return dailyStats.map((day) => {
      const count = (day._sum.problemsSolved ?? 0) + (day._sum.commits ?? 0);
      const level = count === 0 ? 0 : Math.ceil((count / maxActivity) * 4);

      return {
        date: day.date.toISOString().split("T")[0],
        count,
        level: Math.min(level, 4),
      };
    });
  }

  /**
   * Get streak information
   */
  static async getStreakInfo(userId: string): Promise<{
    current: number;
    longest: number;
    lastActivityDate: Date | null;
    streakDates: string[];
  }> {
    // Get all distinct activity dates
    const entries = await prisma.trackerEntry.findMany({
      where: { userId },
      orderBy: { date: "desc" },
      select: { date: true },
      distinct: ["date"],
    });

    if (entries.length === 0) {
      return {
        current: 0,
        longest: 0,
        lastActivityDate: null,
        streakDates: [],
      };
    }

    const today = new Date();
    today.setHours(0, 0, 0, 0);

    const dates = entries.map((e) => {
      const d = new Date(e.date);
      d.setHours(0, 0, 0, 0);
      return d;
    });

    // Calculate current streak
    let currentStreak = 0;
    const streakDates: string[] = [];

    for (let i = 0; i < dates.length; i++) {
      const expectedDate = new Date(today);
      expectedDate.setDate(expectedDate.getDate() - currentStreak);
      expectedDate.setHours(0, 0, 0, 0);

      const diffDays = Math.floor(
        (expectedDate.getTime() - dates[i].getTime()) / (1000 * 60 * 60 * 24)
      );

      if (i === 0 && diffDays > 1) {
        break;
      }

      if (diffDays === 0 || (i === 0 && diffDays === 1)) {
        currentStreak++;
        streakDates.push(dates[i].toISOString().split("T")[0]);
      } else {
        break;
      }
    }

    // Calculate longest streak
    let longestStreak = 0;
    let tempStreak = 0;

    for (let i = 0; i < dates.length; i++) {
      if (i === 0) {
        tempStreak = 1;
      } else {
        const diffDays = Math.floor(
          (dates[i - 1].getTime() - dates[i].getTime()) / (1000 * 60 * 60 * 24)
        );

        if (diffDays === 1) {
          tempStreak++;
        } else {
          longestStreak = Math.max(longestStreak, tempStreak);
          tempStreak = 1;
        }
      }
    }
    longestStreak = Math.max(longestStreak, tempStreak);

    return {
      current: currentStreak,
      longest: longestStreak,
      lastActivityDate: dates[0] || null,
      streakDates,
    };
  }

