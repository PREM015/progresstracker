  /**
   * Merge entries (combine values from sync with existing)
   */
  static async mergeEntry(
    id: string,
    newData: Partial<TrackerEntryInput>,
    strategy: "replace" | "add" | "max" = "max"
  ) {
    const existing = await prisma.trackerEntry.findUnique({
      where: { id },
    });

    if (!existing) {
      throw new Error("Entry not found");
    }

    const numericFields = [
      "problemsSolved",
      "problemsAttempted",
      "easyProblems",
      "mediumProblems",
      "hardProblems",
      "commits",
      "pullRequests",
      "pullRequestsMerged",
      "issuesOpened",
      "issuesClosed",
      "codeReviews",
      "linesOfCode",
      "projectsStarted",
      "projectsCompleted",
      "coursesStarted",
      "coursesCompleted",
      "lessonsCompleted",
      "modulesCompleted",
      "certificationsEarned",
      "quizzesTaken",
      "quizzesPassed",
      "articlesRead",
      "tutorialsCompleted",
      "documentationPages",
      "applicationsSubmitted",
      "applicationsViewed",
      "interviewsScheduled",
      "interviewsCompleted",
      "offersReceived",
      "contestsParticipated",
      "contestsCompleted",
      "hackathonsJoined",
      "hackathonsCompleted",
      "mentoringSessions",
      "helpGiven",
      "helpReceived",
      "postsWritten",
      "commentsWritten",
      "timeSpent",
      "focusTime",
    ] as const;

    const mergedData: TrackerEntryUpdateInput = {};

    for (const field of numericFields) {
      const existingValue = (existing as Record<string, unknown>)[field] as number ?? 0;
      const newValue = (newData as Record<string, unknown>)[field] as number | undefined;

      if (newValue !== undefined) {
        switch (strategy) {
          case "replace":
            (mergedData as Record<string, unknown>)[field] = newValue;
            break;
          case "add":
            (mergedData as Record<string, unknown>)[field] = existingValue + newValue;
            break;
          case "max":
            (mergedData as Record<string, unknown>)[field] = Math.max(existingValue, newValue);
            break;
        }
      }
    }

    // Merge arrays (tags, topics, languages)
    if (newData.tags) {
      mergedData.tags = [...new Set([...existing.tags, ...newData.tags])];
    }
    if (newData.topics) {
      mergedData.topics = [...new Set([...existing.topics, ...newData.topics])];
    }
    if (newData.languages) {
      mergedData.languages = [...new Set([...existing.languages, ...newData.languages])];
    }

    // Non-numeric fields (replace if provided)
    if (newData.notes && !existing.notes) {
      mergedData.notes = newData.notes;
    }
    if (newData.mood) {
      mergedData.mood = newData.mood;
    }
    if (newData.rating !== undefined) {
      mergedData.rating = newData.rating;
    }
    if (newData.rank !== undefined) {
      mergedData.rank = newData.rank;
    }

    return this.updateEntry(id, mergedData);
  }

